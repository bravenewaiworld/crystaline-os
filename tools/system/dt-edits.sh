#!/bin/sh
# Generate the kernel's built-in device-tree edits (linux/drivers/of/fdt_edits.h): run
# system/board/brick/dt-tweaks.sh on the device tree in TrimUI's boot package with fdtput and fdtget
# recorded (dt-edits-record), and write what it did as a C table. OUT is replaced only when its
# content changes, so the kernel isn't rebuilt for nothing.
# Usage: dt-edits.sh <boot_package.fex> <out.c>       DT_TWEAKS overrides the script (for tests).
set -eu
PKG=$1 OUT=$2
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
TWEAKS=${DT_TWEAKS:-$ROOT/system/board/brick/dt-tweaks.sh}
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT

python3 -I "$ROOT/tools/sdboot/toc1.py" "$PKG" 0 "$TMP/pkg" >/dev/null   # 0 = byte offset in the file
cp "$TMP/pkg/dtb.bin" "$TMP/tree.dtb"
mkdir "$TMP/bin"
for t in fdtput fdtget; do
	command -v $t >/dev/null || { echo "dt-edits.sh: needs $t (the device-tree-compiler package)" >&2; exit 1; }
	ln -s "$ROOT/tools/system/dt-edits-record" "$TMP/bin/$t"
done
DT_EDITS_FDTPUT=$(command -v fdtput) DT_EDITS_FDTGET=$(command -v fdtget)
export DT_EDITS_FDTPUT DT_EDITS_FDTGET DT_EDITS_LOG=$TMP/log
: >"$DT_EDITS_LOG"
PATH="$TMP/bin:$PATH" "$TWEAKS" "$TMP/tree.dtb"
if grep -q '^error' "$DT_EDITS_LOG"; then
	echo "dt-edits.sh: dt-tweaks.sh does something the kernel can't redo (see above)" >&2; exit 1
fi

sha() { sha256sum "$1" | cut -c1-12; }
ID="dt-tweaks $(sha "$TWEAKS") on stock $(sha "$TMP/pkg/dtb.bin")"
# Initializers in struct fdt_edit's field order (linux/drivers/of/fdt_edits.h).
awk -F '\t' -v id="$ID" '
	function bytes(h,   s, i) {	# hex digits -> C string literal of those bytes, and its length
		for (i = 1; i < length(h); i += 2) s = s "\\x" substr(h, i, 2)
		return "\"" s "\", " length(h) / 2
	}
	BEGIN {
		print "/* Generated by tools/system/dt-edits.sh from system/board/brick/dt-tweaks.sh. */"
		print "#include \"fdt_edits.h\""
		print ""
		print "const struct fdt_edit fdt_edits[] = {"
	}
	$1 == "set" {
		printf "\t{ FDT_EDIT_SET, \"%s\", \"%s\", %s, %s, %s },\n", $2, $3, bytes($4),
			$5 == "-" ? "NULL, -1" : bytes($5), $6 ? "true" : "false"
	}
	$1 == "expect" { printf "\t{ FDT_EDIT_EXPECT, \"%s\", \"%s\", %s },\n", $2, $3, bytes($4) }
	$1 == "delete" { printf "\t{ FDT_EDIT_DELETE, \"%s\", \"%s\" },\n", $2, $3 }
	$1 == "node"   { printf "\t{ FDT_EDIT_NODE, \"%s\" },\n", $2 }
	END {
		print "};"
		print "const int fdt_edits_count = sizeof(fdt_edits) / sizeof(fdt_edits[0]);"
		print "const char fdt_edits_id[] = \"" id "\";"
	}' "$DT_EDITS_LOG" >"$TMP/out.c"
cmp -s "$TMP/out.c" "$OUT" 2>/dev/null || mv "$TMP/out.c" "$OUT"
